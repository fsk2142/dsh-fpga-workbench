#!/usr/bin/env node
/**
 * 清理提交信息里的「对话痕迹」，供 `git filter-branch --msg-filter` 调用。
 *
 * 为什么需要它：这个仓库的提交信息里长期写着「用户 2026-10-21：…」「用户报障…」
 * 这类句子，把「AI 在与具体用户对话」这件事公开在 GitHub 上（用户 2026-10-21
 * 提出隐私顾虑）。改写只动**提交信息文本**，不动任何文件内容。
 *
 * 改写规则（保守：只删引用框架，保留技术内容）：
 * - `用户 YYYY-MM-DD：` / `用户报障「…」` / `用户原话「…」` → 删掉这个框架，句子本身若
 *   承载技术信息就保留其后的描述；
 * - `用户要求` / `用户确认` / `用户所见` → 换成中性主语（需求 / 实测 / 实际）；
 * - 孤立的日期署名（`（2026-10-21 用户报障）`）→ 删掉整段。
 *
 * 用法：git filter-branch --msg-filter 'node scripts/scrub-commit-msg.mjs'
 */
let input = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => {
  input += chunk;
});

/** 去掉引用框架，保留技术描述。 */
function scrub(message) {
  let text = message;

  // 0. **标题行基本不动，但真实用户路径要清**。
  //
  // 实测确认（2026-10-21）：通用替换 `用户 → 需求` 会打坏标题里的**专有名词**：
  //   · `删除用户预设目录同步链路` → `删除需求预设目录同步链路`
  //     （`用户预设目录` 是 DSH 的概念，改了就不通）
  //   · `用户模板层级标记` → `需求模板层级标记`（同上）
  //   · `告诉用户怎么装` → `告诉需求怎么装`（这里「用户」是真人，改了语义就丢了）
  // 而标题是 GitHub 上**唯一默认可见**的部分 —— 改坏它比留着「用户」二字代价更大。
  //
  // **唯一例外**：标题里真的写着用户名路径（`\C:\Users\<name>\AppData\Roaming`）。
  // 那不是「泛指的用户」，是这台机器的主目录 —— 必须换成占位符。
  // 注意这里举例**不能写真实的用户名**：这个文件是公开的，举例本身就是泄漏
  // （2026-10-22 的自查抓到过一次 —— 清理历史时把真实路径写进了注释）。
  // 只替换这一种形态，不做任何 `用户` 的通用替换。
  text = text.replace(/(?:\\?[A-Za-z]:)?[\\/]+Users[\\/]+[^\\/\s]+/gu, "<用户目录>");

  // 只清理正文：第一个空行之后才动手。
  //
  // **没有正文的提交也要清理一行标题之外的东西吗？** 不用 —— 标题受保护。
  // 但注意：这里的 return 只针对"整条信息只有一行"。真实提交里标题后面
  // 通常紧跟空行，所以绝大部分会走下面的正文分支。

  /**
   * 标题行的**受限**清理（2026-10-30 追加）。
   *
   * 原规则完全不碰标题，依据是「通用替换 `用户 → 需求` 会打坏专有名词」
   * （`用户预设目录` / `用户模板层级`）。那个顾虑成立，所以这里**不做通用替换**，
   * 只处理一种形态：**括号里的对话注记**。
   *
   * ```
   * fix(设置): 仿真器下拉去掉 Verilator(用户口径:仿真不用它)
   *   → fix(设置): 仿真器下拉去掉 Verilator(仿真不用它)
   *
   * feat: ... + 新增 init-scaffold(用户要求)
   *   → feat: ... + 新增 init-scaffold
   * ```
   *
   * 括号注记是**元信息**，去掉不影响标题的技术含义；而专有名词里的「用户」不在括号里，
   * 不会被碰到。
   */
  const scrubTitle = (line) => {
    let out = line;
    // ① 标题里**不在括号内**的「按用户要求 / 按用户口径」→ 压成「按需求」。
    //    `按用户要求重排` → `按需求重排`（读得通，且不暴露对话）。
    //    只认「按用户X」这个搭配 —— 孤立的 `用户` 可能是专有名词（用户预设目录）。
    out = out.replace(/按用户(?:要求|定案|口径|指出|确认|反馈|报障)/gu, "按需求");
    // ② **顺序要紧**：先处理「带内容」的形态 `(用户口径:xxx)` —— 去掉注记前缀、保留内容；
    // 再处理「纯注记」形态 `(用户要求)` —— 整段删掉。
    // 反过来的话，第一条规则会把带内容的那种整段吃掉（实测踩到）。
    out = out.replace(
      /([（(])\s*(?:按|并|且|及)?\s*用户(?:要求|定案|口径|指出|确认|反馈|报障)\s*[：:]\s*/gu,
      "$1"
    );
    // 括号里**只含**对话注记（可带「按/并/且」等连词）→ 整段删掉
    //   覆盖 `(用户要求)` / `（按用户要求）` / `(并按用户要求补)` / `(且按用户定案)`
    out = out.replace(
      /[（(][^（()）]*?(?:按|并|且|及)?\s*用户(?:要求|定案|口径|指出|确认|反馈|报障)[^（()）]*?[)）]/gu,
      ""
    );
    // 去掉注记后可能出现空括号 `()` 或多余空格
    out = out.replace(/[（(]\s*[)）]/gu, "").replace(/[ \t]{2,}/gu, " ");
    return out.replace(/[\s,，、]+$/u, "").trimEnd();
  };

  const split = text.indexOf("\n\n");
  if (split < 0) {
    // 单行提交（只有标题）：路径清理 + 受限的标题清理。
    return scrubTitle(text);
  }
  const title = scrubTitle(text.slice(0, split));
  text = text.slice(split);


  // 1. `用户 YYYY-MM-DD：` 开头的整行删掉（原话本身没有技术价值）。
  //    用 [^\n]* 而不是 `.`（后者在 dotall 缺失时行为依赖标志，这里显式只吃一行）。
  text = text.replace(/^[^\n]*用户\s*20\d{2}-\d{2}-\d{2}[^\n]*\n?/gmu, "");

  // 2. 括号里的用户署名：`（2026-10-21 用户报障）` / `（用户要求）` → 删掉。
  text = text.replace(/[（(]\s*20\d{2}-\d{2}-\d{2}\s*用户[^)）]*[)）]/gu, "");
  text = text.replace(/[（(]\s*用户(?:要求|报障|反馈)[^)）]*[)）]/gu, "");

  // 3. `用户报障「…」` / `用户原话「…」` 在句首：改成「实际现象是「…」」，
  //    比直接删掉前缀好读（否则句子会以一个孤零零的引号开头）。
  text = text.replace(/用户(?:报障|反馈|原话|说)([：:]?\s*「)/gu, "实际现象是$1");
  // 其余 `用户说` / `用户要求` 之类先落成中性词，再统一处理。
  text = text.replace(/用户(?:报障|反馈|原话|说)[：:]?\s*/gu, "");

  // 4. 「经用户确认」这类短语换成读得通的表述（「经需求确认」很别扭）。
  //    注意后面可能已经跟了「实测」，剥掉重复。
  text = text.replace(/经用户(?:确认|反馈|要求)/gu, "经实测");
  text = text.replace(/经实测与实测/gu, "经实测");
  // `用户口径` 是**生造词的来源**：「用户口径 X」→「需求口径 X」在中文里不成立。
  // 本仓库有 25 处，实测确认过 —— 必须先于下面的通用规则处理。
  //   · 带日期署名的行：整句删掉（那是对话框架，没有技术价值）；
  //   · 后面跟冒号的：落成「要求：」；
  //   · 其余：落成「设计取向」（「这个设计取向是…」读得通）。
  text = text.replace(/^[^\n]*用户口径\s*20\d{2}-\d{2}-\d{2}[：:][^\n]*\n?/gmu, "");
  text = text.replace(/用户口径[：:]\s*/gu, "要求：");
  text = text.replace(/用户口径/gu, "设计取向");
  // `用户要求：X` 单独成句时「按需求：」很别扭 —— 先落成「要求：」；
  // 其余 `用户要求 X` / `按用户要求` → `按需求`（避免「需求要求」叠词）。
  text = text.replace(/用户要求[：:]\s*/gu, "要求：");
  text = text.replace(/按?用户要求/gu, "按需求");
  text = text.replace(/用户/g, "需求");

  // 4b. **第三人称指代**：比「用户」更容易暴露"AI 在与某个人对话"。
  //     实测漏网（2026-10-21 自检抓到）：`这正是**他**最初的原话——「…」`。
  //     这类句子把「他/她」当主语，读者立刻知道有个具体的人。整句删掉最干净 ——
  //     原话本身没有技术价值（技术结论在同一段的别处）。
  text = text.replace(/^[^\n]*(?:他|她)(?:最初|当时|之前|自己)?的?原话[^\n]*\n?/gmu, "");
  // `他/她` + 动词的句子（`他说` / `他希望` / `他认为`）→ 换成「要求」。
  // 用「要求」而不是「需求」：`需求这个按钮要点得动` 读不通，`要求这个按钮要点得动` 才顺。
  text = text.replace(/(?:他|她)(?:说|要求|希望|认为|反馈|报障|确认|决定)/gu, "要求");
  // `原话` 这个词本身就是引用框架 —— 剩下的零星出现直接抹掉。
  text = text.replace(/的?原话[：:]?\s*/gu, "");

  // 5. 第一轮改写后仍会残留的几种痕迹（2026-10-21 实测发现）：
  //    - `需求二次报障：「…」` → 换成「实际现象是「…」」；
  //    - `按需求（原话）：` → 整行去掉（原话本身没有技术价值）；
  //    - 行首孤立的 `报障：` / `报障「` → 换成「实际现象」。
  text = text.replace(/需求(?:二次|再次|又)?报障([：:]?\s*「)/gu, "实际现象是$1");
  text = text.replace(/^[^\n]*按需求[（(]原话[)）][：:]?[^\n]*\n?/gmu, "");
  text = text.replace(/^(\s*)报障([：:]|\s*「)/gmu, "$1实际现象是：");
  text = text.replace(/需求(?:二次|再次|又)?报障[：:]?\s*/gu, "");
  // 句子中间残留的 `报障时` / `报障后`：整体替换（只替换「报障」会把后面的时/后留下，
  // 变成「出问题后后」这种叠字 —— 2026-10-21 实测踩到）。
  text = text.replace(/报障时/gu, "出问题时");
  text = text.replace(/报障后/gu, "出问题后");
  text = text.replace(/出问题时时/gu, "出问题时");
  text = text.replace(/出问题后后/gu, "出问题后");

  // 6. 压缩因删除产生的空行（连续 3 个以上换行 → 2 个）。
  text = text.replace(/\n{3,}/gu, "\n\n");

  // 7. 去掉行尾空白与文件首尾空行。
  text = text
    .split("\n")
    .map((line) => line.replace(/\s+$/u, ""))
    .join("\n")
    .replace(/^\n+/u, "");

  // 8. 把标题原样接回去。必须有**一个空行**分隔（`\n\n`）——
  //    早先版本把正文前的 `^\n+` 也剥掉，拼回去就变成 `标题正文` 粘在一起（实测踩到）。
  //    正文若被清空，就只剩标题（git 允许只有标题）。
  const cleanedBody = text.replace(/\n+$/u, "");
  return cleanedBody === "" ? `${title}\n` : `${title}\n\n${cleanedBody}\n`;
}

process.stdin.on("end", () => {
  process.stdout.write(scrub(input));
});
