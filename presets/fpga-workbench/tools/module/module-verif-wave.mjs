// 验证环节:打开波形 GUI,让人亲眼排查问题(**交互式**,不是批处理)。
//
// 为什么单独一条:批处理跑完只留日志与数据文件,"看一眼波形"是人工排查的另一条腿 ——
// 用户说"要看波形"时必须真有一条能打开的手段。旧包的做法是 `vsim -gui` 编完直接开 GUI,
// 这里照同一条路:编好 → 开 GUI → 把信号加进 wave 窗口 → 停住等人操作。
//
// 用法:
//   node module-verif-wave.mjs <模块根> [模块名] [--sim-path <仿真器>] [--tb <测试平台>]
//                       [--out <脚本相对路径>] [--dry-run]
// 退出码:0 已打开 / 已生成;1 找不到测试平台或设计文件;2 参数或环境不对
//
// 两个刻意的边界:
//   · **不自动 run**:GUI 打开后停在 0 时刻,由人决定跑多久、看哪段 —— 与批处理 run.do 互补
//   · **只编不跑**:编译顺序按目录聚合(每个目录内的文件按名字排),多目录工程要用 --tb 指平台;
//     顺序真的对不上时,先按 run.do 的顺序手工编一遍再开 GUI(见 fpga-module-verif)
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, sep } from "node:path";
import { pathToFileURL } from "node:url";

/** HDL 源码扩展名(与 rtl-check 一致:SystemVerilog / Verilog)。 */
const HDL = /\.(sv|v)$/iu;

/** 跳过的目录:生成物、库、版本控制等(与 rtl-check 的 SKIP_DIRS 同一个口径)。 */
const SKIP_DIRS = new Set([
  "history", ".xil", ".git", "__pycache__", "work", "_synth_gate", "_ip_gen",
  "synth_gate.gen", ".srcs", ".runs", ".hw", ".ip_user_files", ".sim", ".cache",
  ".nano", "rerun", "node_modules", "ip", "obj_dir"
]);

/** 平台名的优先级:顶层平台比子模块平台更适合看波形。 */
const TB_PRIORITY = [
  { test: /^tb_top_/iu, rank: 0 },
  { test: /^tb_(?!sub_|top_)/iu, rank: 1 },
  { test: /^tb_sub_/iu, rank: 2 }
];

/** 解析命令行。位置参数只取第一个选项之前的那些 —— 否则 `--sim-path <路径>` 的值会被当成模块名。 */
function parseArgs(argv) {
  const positional = [];
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg.startsWith("-")) break;
    positional.push(arg);
  }
  const value = (flag) => (argv.includes(flag) ? argv[argv.indexOf(flag) + 1] : undefined);
  return {
    root: positional[0],
    name: positional[1],
    simPath: value("--sim-path"),
    tb: value("--tb"),
    out: value("--out") ?? "wave.do",
    dryRun: argv.includes("--dry-run")
  };
}

/** 列出目录下的 HDL 文件(不递归、已排序)。 */
function hdlIn(dir) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .filter((entry) => entry.isFile() && HDL.test(entry.name))
    .map((entry) => join(dir, entry.name))
    .sort();
}

/** 递归列出 HDL 文件(跳过程序生成物与库目录)。 */
function hdlDeep(dir) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const out = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name.toLowerCase()) || entry.name.startsWith(".")) continue;
      out.push(...hdlDeep(full));
    } else if (entry.isFile() && HDL.test(entry.name)) {
      out.push(full);
    }
  }
  return out.sort();
}

/**
 * 挑一个测试平台:显式 `--tb` 优先,否则在 `verif/` 下按 tb_top_ → tb_ → tb_sub_ 找。
 * @param verifDir - `verif/` 目录。
 * @param explicit - `--tb` 给的文件名或路径(相对 `verif/` 或模块根)。
 * @param moduleRoot - 模块根(用于解析显式路径)。
 * @returns 绝对路径;找不到时为 undefined。
 */
function pickTestbench(verifDir, explicit, moduleRoot) {
  if (explicit !== undefined) {
    const candidates = [join(verifDir, explicit), join(moduleRoot, explicit), explicit];
    return candidates.find((path) => existsSync(path) && HDL.test(path));
  }
  const found = hdlIn(verifDir).map((file) => ({
    file,
    rank: TB_PRIORITY.find((rule) => rule.test.test(join(file).split(sep).pop()))?.rank ?? 3
  }));
  found.sort((left, right) => left.rank - right.rank || left.file.localeCompare(right.file));
  return found[0]?.file;
}

/**
 * 收集要编译的设计文件:`rtl/` 下的全部 HDL(递归;`rtl/ip/` 里的厂商代码也编,否则找不到模块)
 * 加上平台自身。
 * @param moduleRoot - 模块根。
 * @param testbench - 平台路径。
 * @returns 绝对路径数组。
 */
function designFiles(moduleRoot, testbench) {
  const rtlDir = join(moduleRoot, "rtl");
  const top = hdlIn(rtlDir);
  const nested = hdlDeep(rtlDir).filter((file) => dirname(file) !== rtlDir);
  // 平铺的工程:rtl/ 顶层就是全部源码;分子目录的工程:连同子目录一起收
  const files = top.length > 0 ? [...top, ...nested] : hdlDeep(rtlDir);
  return [...new Set([...files, testbench])];
}

/** 相对模块根的路径(用 `/` 分隔,写进 .do 时跨平台)。 */
function rel(moduleRoot, file) {
  return relative(moduleRoot, file).split(sep).join("/");
}

/**
 * 生成 ModelSim 的 `wave.do`:**编译 + 开 GUI + 加波形 + 停在 0 时刻**(不自动 run)。
 *
 * 路径是实测踩出来的,分两条:
 * · 源码路径用**绝对路径**(`/` 分隔)—— 工作库与波形都要落在 `verif/`(与 run.do 的结果同处),
 *   脚本一开始就 `cd verif`,所以相对模块根的路径在这里对不上;
 * · 全程留在 `verif/` 里别切走 —— 切走再开 GUI 会"Error loading design"(工作库不在这里)。
 * @param files - 要编译的文件(绝对路径)。
 * @param top - 顶层模块名。
 * @param verifDirSlash - `verif/` 相对模块根的名称(默认 `verif`)。
 * @returns .do 正文。
 */
function modelSimDo(files, top, verifDirSlash = "verif") {
  // 注释一律 ASCII:ModelSim 的 Tcl 不按 UTF-8 读 .do(实测:哪怕带 BOM,中文注释行也会被
  // 报成 `invalid command name "?#"` 并且中止在那一行)。给人看的解释放在控制台输出里。
  return [
    "# Generated by verif-wave.mjs -- compile, open the GUI, add waves, stop at time 0.",
    "# Type `run -all` (or `run 1us`) to simulate; `delete wave *` then re-add to change signals.",
    "onerror {resume}",
    `cd "${verifDirSlash}"`,
    "if {[file exists work]} { catch {vdel -lib work -all} }",
    "vlib work",
    ...files.map((file) => `vlog -sv "${file}"`),
    `vsim -gui -voptargs="+acc=rn" ${top}`,
    "log -r /*",
    "add wave -r /*",
    "configure wave -signalnamewidth 1",
    "wave refresh",
    ""
  ].join("\n");
}

/** 解析 --sim-path 指向哪种仿真器(目录 → 名字;找不到已知名字时 undefined)。 */
function simulatorKind(simPath) {
  if (simPath === undefined) return undefined;
  const lower = simPath.toLowerCase();
  if (lower.includes("vsim") || lower.includes("modelsim") || lower.includes("questa")) return "modelsim";
  if (lower.includes("xsim") || lower.includes("vivado")) return "xsim";
  return undefined;
}

/** 入口。 */
function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.root === undefined) {
    console.error("用法:node module-verif-wave.mjs <模块根> [模块名] [--sim-path <仿真器>] [--tb <测试平台>] [--out <脚本相对路径>] [--dry-run]");
    return 2;
  }
  const moduleRoot = args.root;
  const verifDir = join(moduleRoot, "verif");
  if (!existsSync(verifDir)) {
    console.error(`找不到 verif/ 目录:${verifDir}`);
    console.error("波形属于验证环节 —— 先按 fpga-module-verif 把测试平台跑起来,再来看波形。");
    return 2;
  }

  const testbench = pickTestbench(verifDir, args.tb, moduleRoot);
  if (testbench === undefined) {
    console.error(`verif/ 下没有测试平台(tb_*.sv / tb_*.v):${verifDir}`);
    console.error("用 verif-new.mjs 起一个,或用 --tb <文件> 指定。");
    return 1;
  }

  const files = designFiles(moduleRoot, testbench);
  if (files.length <= 1) {
    console.error(`rtl/ 下没有 HDL 源码可编:${join(moduleRoot, "rtl")}`);
    return 1;
  }

  const top = args.name ?? testbench.split(sep).pop().replace(HDL, "");
  const kind = simulatorKind(args.simPath);
  const outPath = join(verifDir, args.out);
  // vlog 收绝对路径(`/` 分隔):脚本一进来就 cd 到 verif/,相对模块根的路径在那里对不上
  const script = modelSimDo(files.map((file) => file.split(sep).join("/")), top);

  if (args.dryRun === true) {
    console.log(`[dry-run] 将写 ${outPath}`);
    console.log(`[dry-run] 顶层模块:${top}(来自 ${rel(moduleRoot, testbench)})`);
    console.log(`[dry-run] 要编译 ${files.length} 个文件:`);
    for (const file of files) console.log(`  ${rel(moduleRoot, file)}`);
    console.log(`[dry-run] 仿真器:${kind ?? args.simPath ?? "(未给 --sim-path)"}(批处理/交互由它决定)`);
    return 0;
  }

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, script);

  console.log(`已生成 ${outPath}`);
  console.log(`  顶层模块:${top}(来自 ${rel(moduleRoot, testbench)})`);
  console.log(`  编译文件:${files.length} 个`);
  if (kind === "xsim" || args.simPath?.toLowerCase().includes("xsim")) {
    console.log("  XSim 请这样开(在该目录下,脚本里是 xvlog/xelab/xsim 三步):");
    console.log(`    & "${args.simPath}" --gui --view wave.do -t ${top}`);
    console.log(`    (xsim 的 Tcl 不接受 add wave —— 波形窗口里手动加信号,或改用 ModelSim)`);
  } else if (kind === "modelsim" || args.simPath === undefined) {
    console.log("  ModelSim 请这样开(GUI 会停住,不自动 run):");
    console.log(`    cd ${verifDir}`);
    console.log(`  & "${args.simPath ?? "<仿真器路径>"}" -do wave.do`);
    console.log("  打开后敲 `run -all` 看全程,或 `run <时长>` 看一段;想换信号 delete wave * 再加。");
  } else {
    console.log("  认不出这个仿真器:脚本按 ModelSim 语法生成,请照你那个工具的 GUI 姿势手动开。");
  }
  return 0;
}

/** 直接跑本文件时才走 CLI;被 import 时什么都不做。 */
const invokedDirectly = process.argv[1] !== undefined
  && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) {
  process.exitCode = main();
}

export { designFiles, modelSimDo, pickTestbench, simulatorKind };
